  function inkRegions(cells, cols) {
    const remaining = new Set(cells);
    const regions = [];
    for (const first of [...remaining].sort((a, b) => a - b)) {
      if (!remaining.delete(first)) continue;
      const region = [first];
      for (let i = 0; i < region.length; i += 1) {
        const cell = region[i], col = (cell - 1) % cols;
        const neighbors = [cell - cols, cell + cols];
        if (col > 0) neighbors.push(cell - 1);
        if (col < cols - 1) neighbors.push(cell + 1);
        neighbors.forEach(next => { if (remaining.delete(next)) region.push(next); });
      }
      regions.push(region.sort((a, b) => a - b));
    }
    return regions;
  }

  function inkBoundaryLoops(region, cols) {
    const cells = new Set(region), edges = [], outgoing = new Map();
    const add = (x, y, dx, dy, direction) => {
      const edge = { start: [x, y], end: [x + dx, y + dy], direction };
      edges.push(edge);
      const key = `${x},${y}`;
      if (!outgoing.has(key)) outgoing.set(key, []);
      outgoing.get(key).push(edge);
    };
    region.forEach(cell => {
      const x = (cell - 1) % cols, y = Math.floor((cell - 1) / cols);
      if (!cells.has(cell - cols)) add(x, y, 1, 0, 0);
      if (x === cols - 1 || !cells.has(cell + 1)) add(x + 1, y, 0, 1, 1);
      if (!cells.has(cell + cols)) add(x + 1, y + 1, -1, 0, 2);
      if (x === 0 || !cells.has(cell - 1)) add(x, y + 1, 0, -1, 3);
    });
    const unused = new Set(edges), loops = [];
    for (const first of edges) {
      if (!unused.has(first)) continue;
      const loop = [];
      let edge = first;
      while (edge && unused.delete(edge)) {
        loop.push(edge.start);
        if (edge.end[0] === first.start[0] && edge.end[1] === first.start[1]) break;
        const options = (outgoing.get(edge.end.join(",")) || []).filter(next => unused.has(next));
        // Follow the region on the right, keeping diagonal contacts and holes separate.
        const order = [1, 0, 3, 2];
        options.sort((a, b) => order.indexOf((a.direction - edge.direction + 4) % 4)
          - order.indexOf((b.direction - edge.direction + 4) % 4));
        edge = options[0];
      }
      loops.push(loop);
    }
    return loops;
  }

