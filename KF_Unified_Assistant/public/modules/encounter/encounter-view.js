  function inkWarningSurrounds(box, seed) {
    const [x, y, width, height] = box, marks = [];
    const horizontal = width > height, vertical = height > width;
    for (const side of ["left", "right", "top", "bottom"]) {
      const count = ((horizontal && ["top", "bottom"].includes(side)) || (vertical && ["left", "right"].includes(side))) ? 2 : 1;
      for (let i = 0; i < count; i += 1) {
        const offset = i * 41 + side.charCodeAt(0), along = count === 2 ? .3 + i * .4 : .42 + inkRandom(seed, offset) * .16;
        const cx = side === "left" ? x + 12 : side === "right" ? x + width - 12 : x + width * along;
        const cy = side === "top" ? y + 12 : side === "bottom" ? y + height - 12 : y + height * along;
        const angle = (["top", "bottom"].includes(side) ? Math.PI / 2 : 0) + (inkRandom(seed, offset + 11) - .5) * .25;
        marks.push(inkWarningBang(cx, cy, 29 + inkRandom(seed, offset + 17) * 4, angle, seed + offset, 1.3, side));
      }
    }
    return marks.join("");
  }
  function inkWarningText(plan, cols) {
    const x = (plan.cells[0] - 1) % cols * 100, y = Math.floor((plan.cells[0] - 1) / cols) * 100;
    const width = plan.vertical ? 100 : plan.cells.length * 100, height = plan.vertical ? plan.cells.length * 100 : 100;
    const chars = [...plan.text];
    const bookends = chars.length > 1 && inkRandom(plan.seed, 43) < .46;
    const endInset = bookends ? 30 : 0;
    const along = ((plan.vertical ? height : width) - endInset * 2) / chars.length;
    const size = Math.min(60, along - (bookends ? 4 : 20)), hand = Math.floor(inkRandom(plan.seed, 31) * 3);
    const angle = (inkRandom(plan.seed, 37) - .5) * .11;
    const letters = chars.map((char, index) => {
      // Text uses one fixed axis and size. Punctuation never changes its centering.
      const cx = plan.vertical ? x + width / 2 : x + endInset + along * (index + .5);
      const cy = plan.vertical ? y + endInset + along * (index + .5) : y + height / 2;
      return inkWarningGlyph(char, [cx - size / 2, cy - size / 2, size, size], plan.seed + index * 31,
        char === "死" ? 1.7 : 1.4, angle, hand);
    }).join("");
    if (bookends) {
      // Turn vertical punctuation sideways so it stays large without shrinking the word.
      const before = plan.vertical ? [x + width / 2, y + 17, Math.PI / 2] : [x + 17, y + height / 2, -.06];
      const after = plan.vertical ? [x + width / 2, y + height - 17, -Math.PI / 2] : [x + width - 17, y + height / 2, .06];
      return `<g data-warning-punctuation="bookends">${letters}${[before, after].map(([cx, cy, rotation], index) => inkWarningBang(
        cx, cy, 72, rotation, plan.seed + 191 + index * 31, 1.65, index ? "after" : "before")).join("")}</g>`;
    }
    return `<g data-warning-punctuation="surround">${letters}${inkWarningSurrounds([x, y, width, height], plan.seed + 71)}</g>`;
  }
