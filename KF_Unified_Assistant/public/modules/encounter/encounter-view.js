  function inkWarningGlyph(character, box, seed, weight, angle = -.06, hand = -1) {
    const family = ["note", "round", "running"][hand < 0 ? Math.floor(inkRandom(seed, 27) * 3) : hand % 3];
    const paths = INK_WARNING_EXTRAS[family]?.[character] || INK_WARNING_GLYPHS[character]
      || INK_WARNING_EXTRAS.base[character] || INK_DRAGON_GLYPHS[character] || INK_MONSTER_GLYPHS[character];
    // Never draw a missing glyph as an exclamation mark; leave it out and mark it for tests.
    if (!paths) return `<g data-warning-glyph="${character}" data-warning-missing="true" data-warning-box="${box.map(inkNumber).join(",")}"></g>`;
    return `<g data-warning-glyph="${character}" data-warning-hand="${family}" data-warning-box="${box.map(inkNumber).join(",")}">${paths.map((stroke, index) => {
      const slant = family === "running" ? .1 : family === "round" ? -.025 : 0;
      const skeleton = stroke.map(([px, py], i) => [50 + (px - 50) * (family === "running" ? .96 : 1) + (50 - py) * slant
        + (inkRandom(seed + index * 7, i + 61) - .5) * 1.2, py + (inkRandom(seed + index * 11, i + 83) - .5) * 1.1]);
      const points = [];
      const tension = family === "round" ? .2 : family === "running" ? .18 : .13;
      for (let i = 0; i < skeleton.length - 1; i += 1) {
        const a = skeleton[i], b = skeleton[i + 1], before = skeleton[Math.max(0, i - 1)], after = skeleton[Math.min(skeleton.length - 1, i + 2)];
        inkBezier(points, a, [a[0] + (b[0] - before[0]) * tension, a[1] + (b[1] - before[1]) * tension],
          [b[0] - (after[0] - a[0]) * tension, b[1] - (after[1] - a[1]) * tension], b, 12);
      }
      const pressure = weight * (family === "round" ? 1.12 : family === "running" ? .88 : 1);
      return `<path d="${inkPenRibbon(points, seed + index * 19, pressure)}" transform="translate(${box[0]} ${box[1]}) scale(${box[2] / 100} ${box[3] / 100}) rotate(${inkNumber(angle * 180 / Math.PI)} 50 50)"/>`;
    }).join("")}</g>`;
  }
  function inkWarningRun(region, cols, verticalFirst) {
    const cells = new Set(region), runs = [];
    for (const vertical of [false, true]) for (const cell of region) {
      const col = (cell - 1) % cols, step = vertical ? cols : 1;
      if (cells.has(cell - step) && (vertical || col > 0)) continue;
      const run = [cell];
      while ((vertical || (run[run.length - 1] - 1) % cols < cols - 1) && cells.has(run[run.length - 1] + step)) run.push(run[run.length - 1] + step);
      runs.push({ cells: run, vertical });
    }
    const cx = region.reduce((sum, cell) => sum + (cell - 1) % cols, 0) / region.length;
    const cy = region.reduce((sum, cell) => sum + Math.floor((cell - 1) / cols), 0) / region.length;
    const distance = run => Math.abs((run.cells[0] - 1) % cols + (run.vertical ? 0 : (run.cells.length - 1) / 2) - cx)
      + Math.abs(Math.floor((run.cells[0] - 1) / cols) + (run.vertical ? (run.cells.length - 1) / 2 : 0) - cy);
    runs.sort((a, b) => b.cells.length - a.cells.length || Number(b.vertical === verticalFirst) - Number(a.vertical === verticalFirst)
      || distance(a) - distance(b) || a.cells[0] - b.cells[0]);
    return runs[0];
  }
  function inkWarningLayout(region, cols, batch, mode) {
    const remaining = new Set(region), plans = [];
    const seedFor = cell => cell * 41 + cols * 73 + batch * 173;
    const longest = inkWarningRun(region, cols, mode === "vertical" || inkRandom(seedFor(region[0]), 19) > .5);
    if (longest.cells.length >= 3 && !["doom", "bang"].includes(mode)
      && (mode !== "mixed" || inkRandom(seedFor(longest.cells[0]), 23) > .2)) {
      const cells = longest.cells.slice(0, 4), seed = seedFor(cells[0]);
      plans.push({ text: inkRandom(seed, 29) < .5 ? "禁止入内" : "此面向敌", cells, vertical: longest.vertical, seed, kind: "word" });
      cells.forEach(cell => remaining.delete(cell));
    }
    for (const cell of region) {
      if (!remaining.has(cell)) continue;
      const seed = seedFor(cell), neighbors = [];
      if ((cell - 1) % cols < cols - 1 && remaining.has(cell + 1)) neighbors.push({ cell: cell + 1, vertical: false });
      if (remaining.has(cell + cols)) neighbors.push({ cell: cell + cols, vertical: true });
      if (neighbors.length && (["urgent", "vertical"].includes(mode) || (mode === "mixed" && inkRandom(seed, 3) < .52))) {
        const next = mode === "vertical" ? neighbors.find(item => item.vertical) || neighbors[0]
          : neighbors[Math.floor(inkRandom(seed, 5) * neighbors.length)];
        plans.push({ text: "危险", cells: [cell, next.cell], vertical: next.vertical, seed, kind: "word" });
        remaining.delete(cell); remaining.delete(next.cell);
      } else {
        const choice = mode === "doom" ? 1 : mode === "bang" ? 2 + Math.floor(inkRandom(seed, 7) * 2)
          : mode === "mixed" ? Math.floor(inkRandom(seed, 7) * 4) : 0;
        plans.push({ text: ["危", "死", "!", "!!!"][choice], cells: [cell], seed,
          kind: ["letter", "letter", "shout", "fill"][choice], vertical: false });
        remaining.delete(cell);
      }
    }
    return plans;
  }
